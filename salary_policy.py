"""Salary-only presentation and confirmation policy; never authorizes a submit."""
from __future__ import annotations

import re
import math

import config

SALARY_QUESTION = "Подскажите, пожалуйста, какая зарплатная вилка предусмотрена для этой позиции?"


def salary_is_missing(vacancy: dict) -> bool:
    value = vacancy.get("salary")
    if isinstance(value, dict):
        return not (value.get("from") or value.get("to"))
    text = str(value or "").strip().casefold()
    return not text or bool(re.search(r"не\s*указ|договор|не\s*определ", text))


def finish_cover(vacancy: dict, cover: str) -> str:
    """Append a question only to a cover, never to employer questionnaire answers."""
    if not getattr(config, "COVER_ASK_SALARY_RANGE", True) or not salary_is_missing(vacancy) or not cover.strip():
        return cover
    # Replace only known generic closings; preserve candidate evidence.
    body = cover.replace(SALARY_QUESTION, "").rstrip()
    endings = ("Обсудим детали?",
               "Если профиль подходит, можно обсудить задачи и формат работы.")
    for ending in endings:
        if body.endswith(ending):
            body = body[:-len(ending)].rstrip()
            break
    return body + "\n\n" + SALARY_QUESTION


def salary_upper_rub(vacancy: dict) -> float | None:
    value = vacancy.get("salary")
    if isinstance(value, dict):
        if str(value.get("currency", "RUR")).upper() not in {"RUR", "RUB", "₽"}:
            return None
        try:
            return float(value["to"]) if value.get("to") else None
        except (ValueError, TypeError):
            return None
    text = str(value or "").casefold().replace("\u00a0", " ").replace("\u202f", " ")
    if re.search(r"\$|€|usd|eur|тенге|kzt|час|смен|сутк|недел", text):
        return None
    numbers = re.findall(r"\d+(?:[ ]\d{3})*(?:[.,]\d+)?", text)
    if not numbers or (len(numbers) == 1 and re.search(r"\bот\b|from|\+", text)):
        return None  # A lower bound cannot prove the upper bound is low.
    upper = float(numbers[-1].replace(" ", "").replace(",", "."))
    if re.search(r"тыс|\bk\b", text):
        upper *= 1000
    return upper if upper > 0 else None


def salary_baseline() -> float | None:
    direction = getattr(config, "ACTIVE_DIRECTION", None) or {}
    raw = direction.get("salary_baseline")
    if raw is None:
        raw = getattr(config, "HH_AUTO_ANSWER_SALARY_BASELINE", "")
    try:
        baseline = float(str(raw).replace(" ", "").replace(",", "."))
    except (ValueError, TypeError):
        return None
    return baseline if math.isfinite(baseline) and baseline > 0 else None


def confirmation_reason(vacancy: dict) -> str:
    notes = []
    upper, baseline = salary_upper_rub(vacancy), salary_baseline()
    if upper is not None and baseline is not None and upper < baseline:
        notes.append(f"Зарплата: вилка ниже планки; верхняя граница {upper:,.0f} ₽, ваша база {baseline:,.0f} ₽. Подтвердите отклик.".replace(",", " "))
    warning = str(vacancy.get("_hh_salary_warning") or "").strip()
    if warning:
        notes.append(f"Предупреждение HH: {warning}")
    return " ".join(notes)


def extract_hh_salary_warning(text: str) -> str:
    # Match HH's own warning, not a salary opinion generated by the matcher.
    normalized = re.sub(r"\s+", " ", str(text or ""))
    match = re.search(r"Скорее всего[,]?\s+(?:вам\s+)?будет отказ[^.!?\n]{0,400}[.!?]?", normalized, re.I)
    return match.group(0).strip() if match else ""


async def read_hh_salary_warning(page) -> str:
    """Read the currently rendered DOM; no clicks, network requests or form writes."""
    body = await page.query_selector("body")
    return extract_hh_salary_warning(await body.inner_text()) if body else ""


async def unapproved_hh_salary_warning(session) -> str:
    warning = await read_hh_salary_warning(session._page)
    if warning and warning != getattr(session, "_approved_salary_warning", ""):
        session._hh_salary_warning = warning
        return warning
    return ""


def warning_result(warning: str) -> dict:
    return {"ok": False, "requires_salary_confirmation": True,
            "salary_warning": warning, "reason": "hh_salary_warning",
            "message": f"Предупреждение HH: {warning} Требуется подтверждение отклика."}
